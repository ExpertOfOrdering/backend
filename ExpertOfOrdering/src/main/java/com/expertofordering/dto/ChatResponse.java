package com.expertofordering.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Data;
import java.util.List;

@Data
@Schema(description = "Response from OpenAI Chat API")
public class ChatResponse {

    @Schema(description = "A list of chat completion choices. Can be more than one if n is greater than 1.")
    private List<Choice> choices;

    @Data
    @Schema(description = "A single choice in the chat completion.")
    public static class Choice {
        @Schema(description = "The index of the choice in the list of choices.", example = "0")
        private int index;

        @Schema(description = "A chat completion message generated by the model.")
        private Message message;
    }

    @Data
    @Schema(description = "The message generated by the model.")
    public static class Message {
        @Schema(description = "The role of the author of this message.", example = "assistant")
        private String role;

        @Schema(description = "The contents of the message.", example = "주문 목록에서 변경하고 싶은 메뉴를 선택하면 옵션을 다시 고를 수 있는 화면으로 이동합니다.")
        private String content;
    }
}
